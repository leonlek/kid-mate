// Generates crayon/scenes.js — portrait 800x1200 scenes built from coloring/pictures.js
// drawings (placed in the middle) + a themed backdrop. Run: node tools/gen_crayon_scenes.js
const fs = require('fs'), vm = require('vm'), path = require('path');
const root = path.join(__dirname, '..');
const ctx = {}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'coloring/pictures.js'), 'utf8') + '\nthis.PICTURES = PICTURES; this.starShape = starShape;', ctx);
const PICS = Object.fromEntries(ctx.PICTURES.map(p => [p.id, p]));
const DY = 210;

// offset absolute-coordinate path data in y
function shiftPath(d, dy) {
  const toks = d.match(/[A-Za-z]|-?\d*\.?\d+/g);
  const out = []; let cmd = '', k = 0;
  const argc = { M: 2, L: 2, C: 6, Q: 4, A: 7, Z: 0, m: 2, l: 2, c: 6, q: 4, a: 7, z: 0 };
  for (const t of toks) {
    if (/[A-Za-z]/.test(t)) { cmd = t; k = 0; out.push(t); continue; }
    let v = +t; const n = argc[cmd] || 2;
    if (cmd === cmd.toUpperCase()) {
      if (cmd === 'A') { if (k % 7 === 6) v += dy; }
      else if (k % 2 === 1) v += dy;
    }
    k = (k + 1) % n; out.push(String(Math.round(v * 10) / 10));
  }
  return out.join(' ');
}
function conv(r, dy, pfx) {
  const o = { id: pfx + r.id, shape: r.shape };
  if (r.shape === 'circle') { o.cx = r.cx; o.cy = r.cy + dy; o.r = r.r; }
  else if (r.shape === 'ellipse') { o.cx = r.cx; o.cy = r.cy + dy; o.rx = r.rx; o.ry = r.ry; }
  else if (r.shape === 'rect') { o.x = r.x; o.y = r.y + dy; o.w = r.w; o.h = r.h; if (r.rx) o.rx = r.rx; }
  else o.d = shiftPath(r.d, dy);
  if (r.noClick) {
    o.noClick = true;
    if (r.fill === '#2d3436') o.fill = '#2d3436';           // solid dark detail
    else if (r.fill === 'none' && r.stroke) o.strokeWidth = r.strokeWidth || 6; // stroked line
    else if (r.stroke) o.strokeWidth = r.strokeWidth || 6;
    else o.strokeWidth = 6;                                  // white ring decor → outline only
  }
  if (r.strokeWidth && !r.noClick) o.strokeWidth = r.strokeWidth;
  return o;
}
const R = (id, x, y, w, h, rx) => ({ id, shape: 'rect', x, y, w, h, ...(rx ? { rx } : {}) });
const C = (id, cx, cy, r) => ({ id, shape: 'circle', cx, cy, r });
const E = (id, cx, cy, rx, ry) => ({ id, shape: 'ellipse', cx, cy, rx, ry });
const Pth = (id, d) => ({ id, shape: 'path', d });
const THEMES = {
  day: () => [R('sky', 0, 0, 800, 1200), C('sun', 660, 140, 80), E('cloud1', 190, 130, 120, 48), E('cloud2', 470, 70, 90, 38), R('ground', 0, 930, 800, 270)],
  sky: () => [R('sky', 0, 0, 800, 1200), C('sun', 130, 130, 80), E('cloud1', 600, 110, 120, 48), E('cloud2', 250, 1040, 130, 50), E('cloud3', 640, 1100, 110, 44)],
  sea: () => [R('water', 0, 0, 800, 1200), Pth('sand', 'M0 1090 Q130 1040 260 1090 Q390 1140 520 1090 Q650 1040 800 1090 L800 1200 L0 1200 Z'), C('bub1', 130, 160, 40), C('bub2', 210, 90, 30), C('bub3', 690, 190, 36)],
  night: () => [R('sky', 0, 0, 800, 1200), C('moon', 640, 130, 70), ctx.starShape('star1', 150, 120, 48, 21), ctx.starShape('star2', 380, 80, 42, 18), R('ground', 0, 960, 800, 240)],
};
// [pictureId, category, theme, shortName?]
const LIST = [
  ['cat', 'animal', 'day'], ['dog', 'animal', 'day'], ['pig', 'animal', 'day'], ['duck', 'animal', 'day'], ['rabbit', 'animal', 'day'],
  ['cow', 'animal', 'day'], ['lion', 'wild', 'day'], ['monkey', 'wild', 'day'], ['bear', 'wild', 'day'], ['elephant', 'wild', 'day'],
  ['dino', 'wild', 'day'], ['frog', 'animal', 'day'], ['owl', 'animal', 'night'], ['bee', 'animal', 'sky'], ['ladybug', 'animal', 'day'],
  ['unicorn', 'animal', 'day'],
  ['goldfish', 'sea', 'sea'], ['whale', 'sea', 'sea'], ['octopus', 'sea', 'sea'], ['crab', 'sea', 'sea'], ['jellyfish', 'sea', 'sea'], ['turtle', 'sea', 'sea'],
  ['tractor', 'vehicle', 'day'], ['firetruck', 'vehicle', 'day'], ['police', 'vehicle', 'day'], ['ambulance', 'vehicle', 'day'],
  ['airplane', 'vehicle', 'sky'], ['helicopter', 'vehicle', 'sky'], ['hotair', 'vehicle', 'sky'], ['tuktuk', 'vehicle', 'day'],
  ['castle', 'place', 'day'], ['lighthouse', 'place', 'sea'], ['pavilion', 'place', 'day'], ['tent', 'place', 'night'], ['krathong', 'place', 'night'], ['kite', 'place', 'sky'],
];
const scenes = LIST.map(([id, cat, theme]) => {
  const pic = PICS[id];
  const bg = THEMES[theme]().map(r => ({ ...r, id: 'bg_' + r.id }));
  const art = pic.regions.map(r => conv(r, DY, ''));
  return { id: 'x-' + id, name: pic.name, cat, regions: [...bg, ...art] };
});
const js = '// GENERATED by tools/gen_crayon_scenes.js — do not edit by hand.\nvar EXTRA_SCENES = ' + JSON.stringify(scenes) + ';\n';
fs.writeFileSync(path.join(root, 'crayon/scenes.js'), js);
console.log(scenes.length, 'scenes,', (js.length / 1024).toFixed(0) + ' KB');
