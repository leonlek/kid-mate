#!/usr/bin/env python3
"""Record every line a game can speak with Azure Thai TTS → <game>/voice/*.mp3 + map.js.

  python3 tools/gen_voice.py solar-system [--voice th-TH-NiwatNeural]

The game lists its own lines: `<game>/index.html?lines` prints them (speechLines()),
read here via headless Chrome. Clip ids hash voice+text, so only new/changed lines
are synthesized and stale clips are deleted. Needs AZURE_SPEECH_* in tools/.tts-keys.
After running, bump CACHE in sw.js.
"""
import argparse, hashlib, html, json, os, re, subprocess, sys, urllib.parse
from xml.sax.saxutils import escape

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tts_compare import load_keys, post

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'


def game_lines(game):
    url = 'file://' + urllib.parse.quote(os.path.join(ROOT, game, 'index.html')) + '?lines'
    dom = subprocess.run([CHROME, '--headless', '--virtual-time-budget=3000', '--dump-dom', url],
                         capture_output=True, text=True, timeout=120).stdout
    m = re.search(r'<pre id="voice-lines">(.*?)</pre>', dom, re.S)
    if not m:
        sys.exit(f'{game}/index.html?lines printed nothing — does it define speechLines()?')
    return json.loads(html.unescape(m.group(1)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('game')
    ap.add_argument('--voice', default='th-TH-PremwadeeNeural')
    ap.add_argument('--rate', default='-8%')
    a = ap.parse_args()
    keys = load_keys()
    url = f"https://{keys['AZURE_SPEECH_REGION']}.tts.speech.microsoft.com/cognitiveservices/v1"
    hdr = {'Ocp-Apim-Subscription-Key': keys['AZURE_SPEECH_KEY'], 'Content-Type': 'application/ssml+xml',
           'X-Microsoft-OutputFormat': 'audio-24khz-48kbitrate-mono-mp3', 'User-Agent': 'kidslen-tts'}

    lines = game_lines(a.game)
    out = os.path.join(ROOT, a.game, 'voice')
    os.makedirs(out, exist_ok=True)
    vmap, made = {}, 0
    for t in lines:
        cid = hashlib.sha1(f'{a.voice}|{a.rate}|{t}'.encode()).hexdigest()[:10]
        vmap[t] = cid
        path = os.path.join(out, cid + '.mp3')
        if os.path.exists(path):
            continue
        ssml = (f"<speak version='1.0' xml:lang='th-TH'><voice name='{a.voice}'>"
                f"<prosody rate='{a.rate}'>{escape(t)}</prosody></voice></speak>")
        with open(path, 'wb') as f:
            f.write(post(url, hdr, ssml.encode('utf-8')))
        made += 1
        print(f'  + {t}')
    keep = {c + '.mp3' for c in vmap.values()}
    stale = [f for f in os.listdir(out) if f.endswith('.mp3') and f not in keep]
    for f in stale:
        os.remove(os.path.join(out, f))
    with open(os.path.join(out, 'map.js'), 'w', encoding='utf-8') as f:
        f.write(f'// generated by tools/gen_voice.py ({a.voice}) — do not edit\n'
                f'window.VOICE_MAP = {json.dumps(vmap, ensure_ascii=False, indent=0)};\n')
    size = sum(os.path.getsize(os.path.join(out, f)) for f in keep)
    print(f'{len(lines)} lines · {made} new · {len(stale)} removed · {size // 1024} KB → {out}')


if __name__ == '__main__':
    main()
