// Pointed petal in local coords (base at origin, tip up), rotated by `a` degrees and placed at (ox,oy)
function petalPath(ox, oy, a, h, w) {
  const r = a * Math.PI / 180, cs = Math.cos(r), sn = Math.sin(r);
  const T = (x, y) => `${Math.round(ox + x * cs - y * sn)} ${Math.round(oy + x * sn + y * cs)}`;
  return `M ${T(0, 0)} C ${T(-w, -h * 0.3)} ${T(-w * 0.6, -h * 0.82)} ${T(0, -h)} C ${T(w * 0.6, -h * 0.82)} ${T(w, -h * 0.3)} ${T(0, 0)} Z`;
}
const petal = (id, ox, oy, a, h, w) => p(id, petalPath(ox, oy, a, h, w));
// Puffy star with rounded tips (k = how far back from the tip the curve starts, 0..1)
function roundStar(id, cx, cy, R, r, n = 5, k = 0.22) {
  const P = [];
  for (let i = 0; i < 2 * n; i++) { const a = -Math.PI / 2 + i * Math.PI / n, rad = i % 2 ? r : R; P.push([cx + rad * Math.cos(a), cy + rad * Math.sin(a)]); }
  const L = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t], f = q => `${Math.round(q[0])} ${Math.round(q[1])}`;
  let d = '';
  for (let i = 0; i < 2 * n; i += 2) {
    const prev = P[(i + 2 * n - 1) % (2 * n)], tip = P[i], next = P[i + 1];
    const a = L(tip, prev, k), b = L(tip, next, k);
    d += (i === 0 ? `M ${f(a)}` : ` L ${f(a)}`) + ` Q ${f(tip)} ${f(b)} L ${f(next)}`;
  }
  return p(id, d + ' Z');
}

