// 🖌️ ระบาย pictures for ผสมสี — data only (the engine is in index.html).
// Canvas 800×800. A picture = regions drawn back→front; each region gets its own
// outline, so a front shape hides the outline behind it. `real` = the colour the
// thing really is (a name from NAMES in index.html) → ⭐ when painted close to it;
// null = any colour is fine. `back: true` = background (left out of the spoken
// "real colours" line). `deco` = ink drawn over the paint (eyes, stripes…);
// `clip: i` keeps a decoration inside region i.
const circ = (cx, cy, r) => `M${cx - r},${cy} a${r},${r} 0 1 0 ${2 * r},0 a${r},${r} 0 1 0 ${-2 * r},0 Z`;
const ell = (cx, cy, rx, ry) => `M${cx - rx},${cy} a${rx},${ry} 0 1 0 ${2 * rx},0 a${rx},${ry} 0 1 0 ${-2 * rx},0 Z`;
const rect = (x, y, w, h) => `M${x},${y} h${w} v${h} h${-w} Z`;
const rr = (x, y, w, h, r) => `M${x + r},${y} h${w - 2 * r} a${r},${r} 0 0 1 ${r},${r} v${h - 2 * r} a${r},${r} 0 0 1 ${-r},${r} h${-(w - 2 * r)} a${r},${r} 0 0 1 ${-r},${-r} v${-(h - 2 * r)} a${r},${r} 0 0 1 ${r},${-r} Z`;
const poly = (pts) => 'M' + pts.map((p) => p.join(',')).join(' L') + ' Z';
const many = (f, list) => list.map((a) => f(...a)).join(' ');
const star5 = (cx, cy, R) => poly([...Array(10)].map((_, i) => { const a = -Math.PI / 2 + i * Math.PI / 5, q = i % 2 ? R * 0.45 : R; return [Math.round(cx + q * Math.cos(a)), Math.round(cy + q * Math.sin(a))]; }));
const band = (cx, cy, Ro, Ri) => `M${cx - Ro},${cy} A${Ro},${Ro} 0 0 1 ${cx + Ro},${cy} L${cx + Ri},${cy} A${Ri},${Ri} 0 0 0 ${cx - Ri},${cy} Z`;
const drip = (x0, x1, y, h, n) => { const w = (x1 - x0) / n; let s = `M${x0},${y} H${x1} V${y + h}`; for (let i = n - 1; i >= 0; i--) s += ` Q${x0 + (i + 0.5) * w},${y + h + 50} ${x0 + i * w},${y + h}`; return s + ' Z'; };
const flame = (cx, y) => `M${cx},${y} C${cx + 32},${y + 40} ${cx + 30},${y + 78} ${cx},${y + 82} C${cx - 30},${y + 78} ${cx - 32},${y + 40} ${cx},${y} Z`;
const frond = (bx, by, tx, ty) => {                       // a palm leaf from the crown to (tx, ty)
  const mx = (bx + tx) / 2, my = (by + ty) / 2 + 30, L = Math.hypot(tx - bx, ty - by), nx = -(ty - by) / L * 38, ny = (tx - bx) / L * 38;
  return `M${bx},${by} Q${(mx + nx) | 0},${(my + ny) | 0} ${tx},${ty} Q${(mx - nx) | 0},${(my - ny) | 0} ${bx},${by} Z`;
};
// decorations
const dot = (x, y, r) => ({ d: circ(x, y, r), fill: true });
const eye = (x, y, r = 14) => [dot(x, y, r), { d: circ(x - r * 0.35, y - r * 0.35, r * 0.33), fill: '#fff' }];
const ln = (d, w = 10, clip) => ({ d, w, clip });

